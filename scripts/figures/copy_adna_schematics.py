#!/usr/bin/env python3
"""Copy the two existing grapevine-adna schematics into a caller-supplied directory.

This script does not generate F1 or F2 from drawing code. It copies the
hand-authored SVG files already stored in figures/. The figures are therefore
not reproducibly generated by this script; they must be edited as SVG (or
replaced by a future generator) if the drawings change.

It only writes F1_damage_patterns_by_library.svg and
F2_adna_decision_route.svg with open(..., "xb"). It does not modify existing files already
in the destination. The destination must exist. Both target paths are checked
with Path.exists() or Path.is_symlink() (so a dangling symlink is treated
as a collision) before any file is written, so a collision cannot leave a
half-written set.
"""
from __future__ import annotations
import sys
from pathlib import Path

def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: copy_adna_schematics.py OUTDIR")
    out = Path(sys.argv[1])
    if not out.is_dir():
        raise SystemExit("OUTDIR must exist and be a directory")
    here = Path(__file__).resolve().parents[2] / "figures"
    names = (
        "F1_damage_patterns_by_library.svg",
        "F2_adna_decision_route.svg",
    )
    sources = []
    destinations = []
    for name in names:
        src = here / name
        dest = out / name
        if not src.is_file():
            raise SystemExit(f"missing source figure: {src}")
        sources.append(src)
        destinations.append(dest)
    existing = [p for p in destinations if p.exists() or p.is_symlink()]
    if existing:
        raise SystemExit(
            "preflight: destination already has "
            + ", ".join(p.name for p in existing)
            + "; refusing to write a partial set"
        )
    for src, dest in zip(sources, destinations):
        data = src.read_bytes()
        with dest.open("xb") as f:
            f.write(data)
        print(dest.name, len(data))

if __name__ == "__main__":
    main()
